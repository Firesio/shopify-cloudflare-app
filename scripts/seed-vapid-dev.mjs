#!/usr/bin/env node
// Gives a LOCAL checkout working web push without any setup: if .dev.vars has no VAPID key pair, generate one and
// append it. Runs before `npm run dev` (predev), like db:seed does for the local admin.
//
//   npm run push:seed-dev
//
// LOCAL ONLY, and it only ever touches the gitignored .dev.vars file in the project directory:
//   - never calls Cloudflare or Shopify, never touches a remote
//   - refuses when CI, WORKERS_CI or NODE_ENV=production is set
//   - never overwrites: an existing public OR private value (even a half-configured pair) is left alone, so a pair
//     you generated with `npm run push:keys` for a shared dev environment is never replaced
// The pair is throwaway: browsers that subscribed against it must re-enable notifications if .dev.vars is deleted.
import { readFile, writeFile } from "node:fs/promises";
import { webcrypto } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PUBLIC_NAME = "VAPID_PUBLIC_KEY";
const PRIVATE_NAME = "VAPID_PRIVATE_KEY";

/** True when the file already defines the name with a non-empty value (commented lines do not count). */
export function hasValue(content, name) {
  return content.split(/\r?\n/).some((line) => {
    const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    return match !== null && match[1] === name && match[2].trim().replace(/^["']|["']$/g, "") !== "";
  });
}

/** The new file content with a pair appended, or null when anything of the pair is already set. */
export function withVapidPair(content, pair) {
  if (hasValue(content, PUBLIC_NAME) || hasValue(content, PRIVATE_NAME)) return null;
  const separator = content === "" || content.endsWith("\n") ? "" : "\n";
  return `${content}${separator}\n# Web push (local dev only). Generated by scripts/seed-vapid-dev.mjs; throwaway.\n${PUBLIC_NAME}=${pair.publicKey}\n${PRIVATE_NAME}=${pair.privateKey}\n`;
}

export async function generatePair() {
  const { subtle } = webcrypto;
  const keys = await subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"]);
  const publicKey = Buffer.from(new Uint8Array(await subtle.exportKey("raw", keys.publicKey))).toString("base64url");
  const jwk = await subtle.exportKey("jwk", keys.privateKey);
  if (publicKey.length !== 87 || typeof jwk.d !== "string" || jwk.d.length !== 43) {
    throw new Error("unexpected key sizes; refusing to write them");
  }
  return { publicKey, privateKey: jwk.d };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.env.CI || process.env.WORKERS_CI || process.env.NODE_ENV === "production") {
    console.log("push:seed-dev: skipped (CI or production environment).");
    process.exit(0);
  }
  const file = join(dirname(fileURLToPath(import.meta.url)), "..", ".dev.vars");
  let content = "";
  try {
    content = await readFile(file, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  const next = withVapidPair(content, await generatePair());
  if (next === null) {
    console.log("push:seed-dev: .dev.vars already has VAPID keys; leaving them alone.");
  } else {
    await writeFile(file, next);
    console.log("push:seed-dev: added a local VAPID key pair to .dev.vars. Restart the dev server to pick it up.");
  }
}
